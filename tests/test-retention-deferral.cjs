'use strict';
const assert=require('node:assert/strict');
module.exports=async function(){
  process.env.KIDBUSTER_TEST_KV='1';
  const {kv,__resetForTests}=await import('../api/_lib/kv-client.js');
  const svc=await import('../api/_lib/license-service.js');
  const {writeImportQueue,readImportQueue}=await import('../api/_lib/krisp-retention.js');
  const {markNewTranscript}=await import('../api/_lib/transcript-retention.js');
  const session=(await import('../api/krisp-session.js')).default;
  const originalNow=Date.now,HOUR=3600000;
  let now=1800000000000;Date.now=()=>now;
  const call=async(key,action,record)=>{
    const res={code:200,status(n){this.code=n;return this;},json(body){this.body=body;return this;}};
    const body=action?{action,...(typeof record==='string'?{meetingId:record}:{record})}:{};
    await session({method:action?'POST':'GET',headers:{'x-app-key':key,host:'synthetic.example'},body,query:{}},res);
    return res;
  };
  try{
    __resetForTests();
    const key=await svc.getOrCreateFreeLicense('retention-deferral@example.test');
    await svc.activateOrRenewPro({licenseKey:key,paymentCustomerId:'synthetic_customer',paymentSubscriptionId:'synthetic_subscription'});
    await call(key);
    const pending='krisp:data:'+key+':pending',matched='krisp:data:'+key+':matchedQueue';
    const legacy={meetingId:'legacy',transcript:'Legacy lesson text',title:'Existing lesson',receivedAt:new Date(now-13*HOUR).toISOString(),assigned:true};
    const fresh=markNewTranscript({meetingId:'fresh',transcript:'New lesson text',title:'New lesson',assigned:true},now);
    await writeImportQueue(matched,[legacy,fresh]);
    const legacyOffer=(await call(key)).body.matched;
    assert.equal(legacyOffer.meetingId,'legacy');
    const oldDeferred=await call(key,'defer',{...legacyOffer,receivedAt:new Date(now).toISOString()});
    assert.equal(oldDeferred.code,200);
    assert.equal(oldDeferred.body.pending[0].receivedAt,legacy.receivedAt);
    assert.equal(oldDeferred.body.pending[0].retentionVersion,undefined,'old inbox item is not shortened to twelve hours');
    await call(key,'ack-matched','legacy');
    const offered=(await call(key)).body.matched;
    assert.equal(offered.meetingId,'fresh');
    now+=HOUR;
    const deferred=await call(key,'defer',{...offered,receivedAt:new Date(now).toISOString()});
    assert.equal(deferred.code,200);
    const saved=deferred.body.pending.find(x=>x.meetingId==='fresh');
    assert.equal(saved.retentionExpiresAt,fresh.retentionExpiresAt,'busy-workspace deferral preserves server receipt time');
    assert.equal(saved.assigned,false);
    const matchedRead=await readImportQueue(matched);
    assert.equal(matchedRead[0].assigned,true,'matched and pending keep independent delivery flags');
    await call(key,'ack-matched','fresh');
    const raw=(await kv.get(pending)).find(x=>x.meetingId==='fresh');
    assert((await kv.get(raw.contentRef)).transcript===fresh.transcript,'ACK of matched copy must preserve pending copy');
    const tampered=await call(key,'defer',{...saved,transcript:'Changed payload'});
    assert.equal(tampered.code,409);
    assert.equal((await readImportQueue(pending)).find(x=>x.meetingId==='fresh').transcript,fresh.transcript);
    const claimed=await call(key,'claim','fresh');
    assert.equal(claimed.code,200);
    const returned=await call(key,'defer',claimed.body.claimed);
    assert.equal(returned.code,200);
    assert.equal(returned.body.pending.find(x=>x.meetingId==='fresh').retentionExpiresAt,fresh.retentionExpiresAt);
    now=fresh.retentionExpiresAt;
    assert.equal(await kv.get(raw.contentRef),null);
    const expired=await call(key,'defer',claimed.body.claimed);
    assert.equal(expired.code,410,'an expired browser copy cannot silently restart retention');
    const final=await call(key);
    assert.deepEqual(final.body.pending.map(x=>x.meetingId),['legacy']);
    console.log('PASS real API: legacy grandfathering, busy-workspace deferral, independent flags, ACK safety and expiry');
    return 0;
  }finally{Date.now=originalNow;__resetForTests();}
};
if(require.main===module) module.exports().then(n=>{process.exitCode=n;}).catch(e=>{console.error(e);process.exitCode=1;});
